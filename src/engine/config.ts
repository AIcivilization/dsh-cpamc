// engine/config.ts — engine.yaml（v8 格式）的归属：dsh-cpamc 只维护自己拥有的那几个键（设计 §6）
//
// 完整管理界面也会改这份配置（经引擎的管理接口写回文件），所以不再整份重新生成：
//   - 文件不存在：生成一份完整的初始配置；
//   - 文件已在：按 YAML 文档读入（保留注释与用户 / 管理界面写的其他键），只改下面这些键，内容没变就不写。
// dsh-cpamc 拥有的键：server.host / server.port、management.*（密钥、本机限定、打开控制台、不自动更新）、
// access.api-keys 里 keys.json 管的那几把、oauth.auth-dir、plugins.enabled / dir 与四个渠道的 enabled、
// 用量统计开关；出站代理只在 dsh-cpamc 这边改了值（setup --proxy）时才写。
//
// 安全底线：api-keys 为空时引擎完全不鉴权（实测），所以没有可用 key 就拒绝写。

import { createHash } from 'node:crypto'
import YAML, { isMap, isSeq, type Document } from 'yaml'
import type { Ctx } from '../context.js'
import { DshModelError } from '../errors.js'
import { L } from '../i18n.js'
import { DSH_KEY_NAME, activeKeys, type KeyStore } from '../keys.js'
import { PLUGIN_IDS } from '../sources.js'
import type { Config, State } from '../state.js'
import { readText, writeInPlace } from '../util/fs.js'
import { pluginsVersionDir } from './components.js'
import { loadManifest } from './install.js'
import { ensureMgmt } from './mgmt.js'

const HEADER = [
  ' 由 dsh-cpamc 生成。可以在完整管理界面里修改；dsh-cpamc 只维护监听地址、管理密钥、',
  ' 它发出的访问 key、凭据目录与四个渠道插件的启用状态，其余设置不会被覆盖。',
  ' Generated by dsh-cpamc. Edit it from the full management interface; dsh-cpamc only maintains the listen address,',
  ' the management key, the access keys it issued, the auth dir and the four channel plugins; everything else is left alone.',
].join('\n')

export function keyHash(key: string): string {
  return createHash('sha256').update(key).digest('hex').slice(0, 32)
}

export interface OwnedInput {
  port: number
  mgmtSecret: string
  authDir: string
  pluginsDir: string
  /** keys.json 里的全部 key（含已吊销的）：已吊销的要从引擎里去掉 */
  keys: KeyStore
  /** 要写的出站代理；undefined = 不动文件里的值 */
  proxy?: string | null
}

/** 初始配置：只在 engine.yaml 不存在时用 */
export function initialDoc(o: OwnedInput): Document {
  const doc = new YAML.Document({
    'config-version': 8,
    server: { host: '127.0.0.1', port: o.port },
    management: { 'allow-remote': false, 'secret-key': o.mgmtSecret, 'disable-control-panel': false, 'disable-auto-update-panel': true },
    access: { 'api-keys': [] },
    oauth: { 'auth-dir': o.authDir },
    routing: { strategy: 'fill-first' },
    ...(o.proxy ? { requests: { 'proxy-url': o.proxy } } : {}),
    plugins: { enabled: true, dir: o.pluginsDir, configs: {} },
    observability: {
      logs: { 'logging-to-file': true, 'logs-max-total-size-mb': 50, 'request-log': false },
      // 用量记录给守护进程统计 key / 来源 / 模型的速度与稳定性；它每 5 秒取一次，保留 10 分钟足够兜住停顿
      usage: { 'usage-statistics-enabled': true, 'redis-usage-queue-retention-seconds': 600 },
    },
  })
  doc.commentBefore = HEADER
  return doc
}

/** 文件里现有的 api-keys（字符串列表；不认识的形状当空） */
export function engineApiKeys(doc: Document): string[] {
  const seq = doc.getIn(['access', 'api-keys'], true)
  if (!isSeq(seq)) return []
  return seq.items.map((i) => String((i as { value?: unknown })?.value ?? i)).filter(Boolean)
}

/**
 * api-keys 合并：别人加的（完整管理界面里加的）原样保留；我们发过的按 keys.json 来——在用的写上、吊销的去掉。
 */
export function mergeApiKeys(existing: string[], keys: KeyStore): string[] {
  const ours = new Set(keys.keys.map((k) => k.key))
  const kept = existing.filter((k) => !ours.has(k))
  const active = activeKeys(keys).map((k) => k.key)
  return [...new Set([...kept, ...active])]
}

/** 只改 dsh-cpamc 拥有的键 */
export function applyOwned(doc: Document, o: OwnedInput): void {
  const set = (path: (string | number)[], value: unknown) => {
    if (doc.getIn(path) !== value) doc.setIn(path, value)
  }
  set(['config-version'], 8)
  set(['server', 'host'], '127.0.0.1')
  set(['server', 'port'], o.port)
  set(['management', 'allow-remote'], false)
  set(['management', 'secret-key'], o.mgmtSecret)
  set(['management', 'disable-control-panel'], false)
  set(['management', 'disable-auto-update-panel'], true)
  set(['oauth', 'auth-dir'], o.authDir)
  set(['plugins', 'enabled'], true)
  set(['plugins', 'dir'], o.pluginsDir)
  for (const id of PLUGIN_IDS) set(['plugins', 'configs', id, 'enabled'], true)
  set(['observability', 'usage', 'usage-statistics-enabled'], true)
  if (o.proxy !== undefined) {
    if (o.proxy) set(['requests', 'proxy-url'], o.proxy)
    else if (doc.hasIn(['requests', 'proxy-url'])) doc.deleteIn(['requests', 'proxy-url'])
  }
  const before = engineApiKeys(doc)
  const merged = mergeApiKeys(before, o.keys)
  if (merged.join('\n') !== before.join('\n') || !isSeq(doc.getIn(['access', 'api-keys'], true))) {
    doc.setIn(['access', 'api-keys'], doc.createNode(merged))
  }
}

/**
 * key 对账（设计 §6 第 4 条）：上次写进引擎、现在却不在引擎里的 key，是在完整管理界面里删掉的——在 keys.json 里标成已吊销。
 * dsh 用的那把除外（dsh 要靠它调模型）：它会被重新写回去。返回被吊销的 key 名。
 */
export function reconcileRemovedKeys(engineKeys: string[], keys: KeyStore, lastWritten: string[]): string[] {
  const inEngine = new Set(engineKeys.map(keyHash))
  const written = new Set(lastWritten)
  const revoked: string[] = []
  for (const k of activeKeys(keys)) {
    const h = keyHash(k.key)
    if (k.name !== DSH_KEY_NAME && written.has(h) && !inEngine.has(h)) {
      k.revokedAt = new Date().toISOString()
      revoked.push(k.name)
    }
  }
  return revoked
}

export interface WriteResult {
  written: boolean
  /** 在完整管理界面里被删掉、已同步成吊销的 key */
  revoked: string[]
}

/**
 * 写 engine.yaml（只动自己的键，内容没变就不写，避免引擎无谓的热重载）。
 * 会就地修改 keys（对账吊销）与 state.engineOwned（记下这次写进去的 key 与代理）；调用方负责落盘。
 */
export async function writeEngineConfig(ctx: Ctx, config: Config, keys: KeyStore, state: State): Promise<WriteResult> {
  if (activeKeys(keys).length === 0) {
    throw new DshModelError('no_api_keys', L('没有可用的 key，拒绝写引擎配置（空 key 列表会让引擎不做鉴权）', 'No active keys; refusing to write engine config (an empty key list disables engine auth)'))
  }
  const mgmt = await ensureMgmt(ctx)
  const manifest = await loadManifest()
  const owned = state.engineOwned ?? { keys: [] }
  const proxyChanged = config.proxy !== undefined && (owned.proxy === undefined || owned.proxy !== config.proxy)
  const input: OwnedInput = {
    port: config.port,
    mgmtSecret: mgmt.secret,
    authDir: ctx.paths.auth,
    pluginsDir: pluginsVersionDir(ctx, manifest.plugins.version),
    keys,
    ...(proxyChanged ? { proxy: config.proxy ?? null } : {}),
  }

  const text = await readText(ctx.paths.engineYaml)
  let doc: Document
  let revoked: string[] = []
  if (text === null || !text.trim()) {
    doc = initialDoc({ ...input, proxy: config.proxy ?? null })
  } else {
    doc = YAML.parseDocument(text)
    if (doc.errors.length || !isMap(doc.contents)) {
      throw new DshModelError('engine_config_invalid', L(`引擎配置解析失败：${doc.errors[0]?.message ?? '不是键值结构'}`, `Engine config could not be parsed: ${doc.errors[0]?.message ?? 'not a mapping'}`), L(`检查 ${ctx.paths.engineYaml}，或在完整管理界面里修正`, `Check ${ctx.paths.engineYaml}, or fix it in the full management interface`))
    }
    revoked = reconcileRemovedKeys(engineApiKeys(doc), keys, owned.keys)
  }
  applyOwned(doc, input)
  state.engineOwned = { keys: activeKeys(keys).map((k) => keyHash(k.key)), proxy: config.proxy ?? null }

  const out = doc.toString()
  if (text === out) return { written: false, revoked }
  // 原地写：保留 inode，让引擎（含 Linux）的 fsnotify 能收到变化并热重载
  await writeInPlace(ctx.paths.engineYaml, out, { owner: ctx.owner })
  return { written: true, revoked }
}
